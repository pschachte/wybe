#!/usr/bin/env python3
"""Parallel equivalent of `make test`.

Runs the final-dump, execution, complex and examples suites concurrently,
writing the same .out files and ERRS report as the shell scripts.

Tests in the same directory can share imported modules, so concurrent
compiles may race on the same .o file.  Any test that fails in the parallel
phase is therefore re-run serially before being reported as a failure.

Usage:  test-cases/run-parallel.py [-j N] [--skip-build]
"""

import argparse
import filecmp
import glob
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import threading
import time
import traceback
from concurrent.futures import ThreadPoolExecutor, as_completed

TEST_DIR = os.path.dirname(os.path.realpath(__file__))
ROOT = os.path.dirname(TEST_DIR)
LIBDIR = "../wybelibs"
WYBEMK = "../wybemk"
TIMEOUT = shutil.which("gtimeout") or "timeout"
DWDIFF_DELIMS = "()<>~!@:?.%#"

PASS, FAIL, NEW = "pass", "fail", "new"
RETRY = "retry"  # display-only: failed in parallel, awaiting serial re-run


def run(cmd, limit, **kw):
    return subprocess.run([TIMEOUT, str(limit), *cmd], **kw)


def dwdiff(exp, out, *extra):
    r = subprocess.run(["dwdiff", *extra, "-c", "-d", DWDIFF_DELIMS, exp, out],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    return r.stdout.decode(errors="replace")


def header(kind, targ, stars=16):
    s = "*" * stars
    return f"\n\x1b[34;1m{s} {kind} {targ} {s}\x1b[0m\n"


def compare(exp, out, report):
    """Return (status, err_text) for an .out file against its .exp file."""
    if not os.path.exists(exp):
        return NEW, ""
    if filecmp.cmp(exp, out, shallow=False):
        return PASS, ""
    return FAIL, report()


# ---------------------------------------------------------------- suites

def final_dump_test(src):
    base = src[:-len(".wybe")]
    out, exp, targ = base + ".out", base + ".exp", base + ".o"
    r = run([WYBEMK, "--log=FinalDump", "--force-all", "-n", "-L", LIBDIR, targ],
            60, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    text = r.stdout.decode(errors="surrogateescape")
    text = re.sub(r"@([A-Za-z0-9_-]*):[0-9:]*", r"@\1:nn:nn", text)
    text = text.replace(os.getcwd(), "!ROOT!")
    text = re.sub(r"\[ [0-9][0-9]* x i8 \]", "[ ?? x i8 ]", text)
    text = re.sub(r"(?m)^(target triple *= *).*", r"\1????", text)
    text = re.sub(r"(?m)^(;; FILE GENERATED BY wybemk).*", r"\1 XXX", text)
    if text and not text.endswith("\n"):
        text += "\n"
    with open(out, "w", errors="surrogateescape") as f:
        f.write(text)

    def report():
        out_lines = text.count("\n")
        with open(exp, errors="replace") as f:
            exp_lines = f.read().count("\n")
        if out_lines <= 20 and exp_lines > 20:
            return header("unexpected output building", targ, stars=12) + text
        return header("difference building", targ) + dwdiff(exp, out, "-C1")

    return compare(exp, out, report)


def execution_test(src):
    targ = src[:-len(".wybe")]
    out, exp, inp, cmdline = (targ + ext for ext in (".out", ".exp", ".in", ".cmdline"))
    if os.path.exists(targ):
        os.remove(targ)
    run([WYBEMK, "--force-all", "-L", LIBDIR, targ], 30,
        stdout=subprocess.DEVNULL)
    cmd = [targ]
    if os.access(cmdline, os.R_OK):
        with open(cmdline) as f:
            cmd += shlex.split(f.read())
    with open(out, "wb") as o:
        stdin = open(inp, "rb") if os.path.exists(inp) else subprocess.DEVNULL
        try:
            run(cmd, 30, stdin=stdin, stdout=o, stderr=subprocess.STDOUT)
        except OSError as e:  # executable wasn't built
            o.write(f"{e}\n".encode())
        finally:
            if stdin is not subprocess.DEVNULL:
                stdin.close()
    return compare(exp, out, lambda: header("difference building", targ) + dwdiff(exp, out))


def example_test(src):
    targ = src[:-len(".wybe")]
    for f in (targ, targ + ".o"):
        if os.path.exists(f):
            os.remove(f)
    r = run([WYBEMK, "--force-all", "-L", LIBDIR, targ], 30,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode == 0:
        return PASS, ""
    # mimic `echo $out` (whitespace collapsed)
    return FAIL, f"Failed to build {targ}\n" + " ".join(r.stdout.decode(errors="replace").split()) + "\n"


def complex_test(case):
    from complex import utils
    func_name, test_file, func = case
    name = f"{os.path.splitext(test_file)[0]}-{func_name}"
    with open(f"./complex/exp/{name}.wybe", "w") as f:
        f.write(f"# Complex test case: {name} File: {test_file}\n")
    out, exp = f"./complex/exp/{name}.out", f"./complex/exp/{name}.exp"
    with open(out, "w") as out_file, tempfile.TemporaryDirectory() as tmp:
        ctx = utils.Context(tmp, ROOT, out_file)
        try:
            func(ctx)
        except Exception:
            ctx.write_section("Error occurred during test execution", traceback.format_exc())
    if not os.path.exists(exp):
        return NEW, ""
    same = subprocess.run(["diff", "-q", "-I", "^source_filename *=.*",
                           "-I", "^target triple *=.*", out, exp],
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0
    return (PASS, "") if same else (FAIL, dwdiff(exp, out))


def collect():
    """Return [(suite_name, [(label, fn, arg)])] in the order make test runs them."""
    for pat in ("final-dump/*.bc", "final-dump/*.o", "final-dump/*.out",
                "execution/*.o", "execution/*.out",
                "../samples/*.o", "../benchmarks/*.o"):
        for f in glob.glob(pat):
            os.remove(f)

    sys.path.insert(0, TEST_DIR)
    from complex import utils  # importing the package registers the test cases

    examples = sorted(glob.glob("../samples/*.wybe")) + sorted(glob.glob("../benchmarks/*/*.wybe"))
    return [
        ("Final Dump", [(f, final_dump_test, f) for f in sorted(glob.glob("final-dump/*.wybe"))]),
        ("Execution", [(f, execution_test, f) for f in sorted(glob.glob("execution/*.wybe"))]),
        ("Complex", [(f"{c[1]}:{c[0]}", complex_test, c) for c in utils.TEST_CASES]),
        ("Examples", [(f, example_test, f) for f in examples]),
    ]


# ---------------------------------------------------------------- display

class Display:
    """A block of per-suite progress bars redrawn in place; messages scroll above it."""

    def __init__(self, suites):
        self.tty = sys.stdout.isatty()
        self.lock = threading.Lock()
        self.stats = {name: {"total": len(tests), PASS: 0, FAIL: 0, NEW: 0, RETRY: 0} for name, tests in suites}
        self.status = ""
        self.drawn = 0
        self.start = time.time()

    def _lines(self):
        width = 30
        lines = []
        for name, s in self.stats.items():
            done = s[PASS] + s[FAIL] + s[NEW] + s[RETRY]
            filled = width * done // max(s["total"], 1)
            colour = "31" if s[FAIL] else ("32" if done == s["total"] else "36")
            bar = f"\x1b[{colour}m{'━' * filled}\x1b[90m{'━' * (width - filled)}\x1b[0m"
            extra = ""
            if s[FAIL]:
                extra += f"  \x1b[31m✗ {s[FAIL]}\x1b[0m"
            if s[RETRY]:
                extra += f"  \x1b[33m⟳ {s[RETRY]} to re-run\x1b[0m"
            if s[NEW]:
                extra += f"  \x1b[33m? {s[NEW]}\x1b[0m"
            lines.append(f"  {name:<11} {bar} {done:>4}/{s['total']:<4}{extra}")
        lines.append(f"  \x1b[90m{time.time() - self.start:6.1f}s  {self.status}\x1b[0m")
        return lines

    def _redraw(self, message=None):
        if not self.tty:
            if message:
                print(message, flush=True)
            return
        buf = f"\x1b[{self.drawn}F\x1b[J" if self.drawn else ""
        if message:
            buf += message + "\n"
        lines = self._lines()
        buf += "\n".join(lines) + "\n"
        self.drawn = len(lines)
        sys.stdout.write(buf)
        sys.stdout.flush()

    def update(self, suite=None, result=None, message=None, status=None):
        with self.lock:
            if suite and result:
                self.stats[suite][result] += 1
            if status is not None:
                self.status = status
            self._redraw(message)

    def retract(self, suite, result):
        with self.lock:
            self.stats[suite][result] -= 1


def run_one(fn, arg):
    try:
        return fn(arg)
    except Exception:
        return FAIL, traceback.format_exc()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-j", "--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--skip-build", action="store_true",
                    help="don't rebuild wybemk and the libraries first")
    args = ap.parse_args()

    os.chdir(ROOT)
    with open("ERRS", "w") as f:
        f.write("Testing run " + time.strftime("%a %b %e %H:%M:%S %Z %Y") + "\n")
    if not args.skip_build:
        print("Building wybemk and libraries...", flush=True)
        for f in glob.glob("wybelibs/*.o") + glob.glob("wybelibs/wybe/*.o"):
            os.remove(f)
        for cmd in (["make", "-s", "wybemk"], ["make", "-s", "wybelibs/wybe/cbits.o"],
                    [TIMEOUT, "60", "make", "-s", "libs"]):
            if subprocess.run(cmd).returncode != 0:
                sys.exit(f"Build failed: {' '.join(cmd)}")

    os.chdir(TEST_DIR)
    suites = collect()
    display = Display(suites)
    results = {}  # (suite, label) -> (status, err)

    def finish(suite, label, status, err, retrying=False):
        results[(suite, label)] = (status, err)
        msg = None
        if status == FAIL and not retrying:
            status = RETRY  # parallel failures may be races; don't report yet
        elif status == FAIL:
            msg = f"  \x1b[31m✗\x1b[0m {suite}: {label}"
        elif status == NEW:
            msg = f"  \x1b[33m?\x1b[0m {suite}: {label} (no .exp file)"
        display.update(suite, status, msg, status=label)

    display.update(status=f"running with {args.jobs} jobs")
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {}
        for suite, tests in suites:
            for label, fn, arg in tests:
                futures[pool.submit(run_one, fn, arg)] = (suite, label, fn, arg)
        for fut in as_completed(futures):
            suite, label, _, _ = futures[fut]
            finish(suite, label, *fut.result())

    # Re-run failures serially to weed out races on shared .o files.
    retry = [t for t in futures.values() if results[(t[0], t[1])][0] == FAIL]
    for i, (suite, label, fn, arg) in enumerate(retry, 1):
        display.update(status=f"re-running {i}/{len(retry)} serially: {label}")
        display.retract(suite, RETRY)
        finish(suite, label, *run_one(fn, arg), retrying=True)

    # Write ERRS in deterministic suite order.
    failed, new = [], []
    with open("../ERRS", "a") as errs:
        for suite, tests in suites:
            for label, _, _ in tests:
                status, err = results[(suite, label)]
                if status == FAIL:
                    failed.append(label)
                    errs.write(err)
                elif status == NEW:
                    new.append(label)

    elapsed = time.time() - display.start
    display.update(status="done")
    print()
    if failed:
        print(f"\x1b[31;1m{len(failed)} FAILED\x1b[0m:")
        for label in failed:
            print(f"    {label}")
        print("See ERRS for differences.")
    else:
        print("\x1b[32;1mALL TESTS PASS\x1b[0m")
    if new:
        print(f"\x1b[33mNew tests\x1b[0m (run ./update-exp to specify expected output):")
        for label in new:
            print(f"    {label}")
    print(f"Finished in {elapsed:.1f}s")
    sys.exit(1 if failed or new else 0)


if __name__ == "__main__":
    main()
